CREATE TABLE IF NOT EXISTS goals (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  task TEXT NOT NULL,
  agents TEXT NOT NULL,
  priority INTEGER NOT NULL DEFAULT 1,
  active INTEGER NOT NULL DEFAULT 0 CHECK(active IN (0,1)),
  max_runs INTEGER NOT NULL DEFAULT 2 CHECK(max_runs BETWEEN 1 AND 2),
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS dispatches (
  id TEXT PRIMARY KEY,
  goal_id TEXT NOT NULL,
  iteration INTEGER NOT NULL CHECK(iteration BETWEEN 1 AND 2),
  job_id TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL,
  verdict TEXT NOT NULL,
  qa_note TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(goal_id,iteration)
);
CREATE TABLE IF NOT EXISTS events (
 id TEXT PRIMARY KEY,
 type TEXT NOT NULL,
 detail TEXT NOT NULL,
 created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL, updated_at TEXT NOT NULL);
